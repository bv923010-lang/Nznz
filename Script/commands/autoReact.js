module.exports.config = {
  name: "autoReact",
  eventType: ["message"],
  version: "3.0.0",
  author: "Belal YT",
  description: "সব message এ random emoji react করে — 300+ emoji",
};

module.exports.handleEvent = async function ({ api, event }) {
  try {
    if (event.type !== "message") return;
    const { messageID, senderID } = event;

    // বট নিজের message এ react করবে না
    if (String(senderID) === String(api.getCurrentUserID())) return;

    // Random emoji select
    const emoji = EMOJIS[Math.floor(Math.random() * EMOJIS.length)];

    // React করো
    await api.setMessageReaction(emoji, messageID, () => {}, true);
  } catch {}
};
